// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// every pre-token protocol below the floor that the watchlist's own rule would keep: no token
// recorded, not a wrapped, staked or bridged product, not an exchange, not a versioned pool. The
// radar finds the early ones the floor leaves out, at any size, and ranks them on the same model.
//
// Implied value follows only from the snapshot's own figures. Four factors, each stated on the
// dashboard so a reader can check the arithmetic row by row:
//
//   band       = the TVL band's multiple: the fraction of TVL a launch is worth shrinks as the
//                protocol gets bigger (a small protocol has more headroom; a giant one is already
//                priced like the market it serves). Under $50M 0.60, $50M-$250M 0.42,
//                $250M-$1B 0.28, $1B and up 0.18.
//   growth     = change_7d clamped to [-50, +100] per cent; 1 + growth x 0.6 / 100.
//                A protocol growing 100% in a week is worth 1.6x its band; one down 50% is 0.7x.
//   maturity   = 0.7 + 0.3 x min(age_days, 1095) / 1095. A protocol that has run longer with no
//                token recorded is more due a launch; a fresh one is discounted. Age unknown: 365.
//   breadth    = 1 + 0.015 x min(chains - 1, 20). More chains means more surface: more users,
//                more places a token would land. One chain is 1.00, twenty-one or more is 1.30.
//
//   implied    = max(1, round(tvl_usd x band x growth x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row. Protocols whose
// token already trades are kept apart in a Live view and shown at the market's own value, never
// mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

